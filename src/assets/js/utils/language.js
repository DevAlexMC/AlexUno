const originals = new WeakMap();
const attributes = ['title', 'placeholder', 'aria-label'];
let language = localStorage.getItem('light-language') === 'en' ? 'en' : 'es';
export function translate(value) {
    const normalized = value.trim().replace(/\s+/g, ' ');
    if (language !== 'en') return value;
    if (Object.prototype.hasOwnProperty.call(dictionary, normalized)) return value.replace(value.trim(), dictionary[normalized]);
    for (const [source, target] of Object.entries(prefixes)) if (value.startsWith(source)) return target + value.slice(source.length);
    return value;
}
function update(node, key, value, write) {
    let record = originals.get(node);
    if (!record) { record = {}; originals.set(node, record); }
    const previous = record[key];
    const source = previous && previous.rendered === value ? previous.source : value;
    const rendered = translate(source);
    record[key] = {source, rendered};
    if (rendered !== value) write(rendered);
}
function scan(root) {
    if (root.nodeType === Node.TEXT_NODE) {
        if (!root.parentElement || root.parentElement.closest('script,style,.instance-name,.light-news-list,#light-auth-name,#light-preview-player-name')) return;
        update(root, 'text', root.data, value => { root.data = value; });
        return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE) return;
    if (root.closest('script,style,.light-news-list')) return;
    if (root.matches('#light-language, #light-login-language')) root.value = language;
    for (const attr of attributes) if (root.hasAttribute(attr)) update(root, attr, root.getAttribute(attr), value => root.setAttribute(attr, value));
    for (const child of root.childNodes) scan(child);
}
export function initLanguage() {
    document.documentElement.lang = language;
    const observer = new MutationObserver(records => {
        for (const record of records) {
            if (record.type === 'childList') for (const node of record.addedNodes) scan(node);
            else scan(record.target);
        }
    });
    observer.observe(document.body, {subtree:true, childList:true, characterData:true, attributes:true, attributeFilter:attributes});
    document.addEventListener('change', event => {
        if (!event.target.matches('#light-language, #light-login-language')) return;
        language = event.target.value === 'en' ? 'en' : 'es';
        localStorage.setItem('light-language', language);
        document.documentElement.lang = language;
        syncLanguageSelector();
        scan(document.body);
    });
    scan(document.body);
}
export function syncLanguageSelector() {
    for (const select of document.querySelectorAll('#light-language, #light-login-language')) select.value = language;
}
